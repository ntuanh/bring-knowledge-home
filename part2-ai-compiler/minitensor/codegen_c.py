"""Stage 5: C code generation.

Input: the loop IR from loopir.py. Output: one C source file containing a
function per kernel and a small `main` harness that creates the inputs, runs
the kernels in order and prints every output tensor.
Called by driver.py, which then compiles the file with `gcc -O2`.

The mapping from loop IR to C is one-to-one: a "for" becomes a for loop, an
"assign" a local float, a "store"/"load" an array access. All tensors are
float32 arrays; buffer names get the prefix t_ so they cannot clash with C
keywords or loop variables.
"""

import math

from .errors import MTError


def cfloat(value):
    if not math.isfinite(value):
        raise MTError("codegen", "a constant is infinite or not a number; cannot generate C for it")
    return repr(float(value)) + "f"


def expr_c(expr):
    kind = expr[0]
    if kind == "load":
        return f"t_{expr[1]}[{expr[2]}]"
    if kind == "var":
        return expr[1]
    if kind == "const":
        return cfloat(expr[1])
    if kind == "max0":
        return f"relu({expr_c(expr[1])})"
    return f"({expr_c(expr[2])} {expr[1]} {expr_c(expr[3])})"


def body_c(statements, indent, declared, lines):
    """`declared` is the set of scalars already declared in an enclosing scope."""
    pad = "    " * indent
    for stmt in statements:
        if stmt[0] == "for":
            var, extent = stmt[1], stmt[2]
            lines.append(f"{pad}for (int {var} = 0; {var} < {extent}; {var}++) {{")
            body_c(stmt[3], indent + 1, set(declared), lines)
            lines.append(f"{pad}}}")
        elif stmt[0] == "assign":
            if stmt[1] in declared:
                lines.append(f"{pad}{stmt[1]} = {expr_c(stmt[2])};")
            else:
                declared.add(stmt[1])
                lines.append(f"{pad}float {stmt[1]} = {expr_c(stmt[2])};")
        else:
            lines.append(f"{pad}t_{stmt[1]}[{stmt[2]}] = {expr_c(stmt[3])};")


def kernel_c(kernel):
    params = [f"const float *t_{name}" for name in kernel["inputs"]] + [f"float *t_{kernel['output']}"]
    lines = [f"/* computes: {', '.join(kernel['nodes'])} */",
             f"static void {kernel['name']}({', '.join(params)})", "{"]
    body_c(kernel["body"], 1, set(), lines)
    lines.append("}")
    return "\n".join(lines)


def generate(graph, lowered, title):
    """Returns the complete C program as a string."""
    out = [f"/* Generated by minitensor: {title}. */", "#include <stdio.h>", "",
           "static inline float relu(float v) { return v > 0.0f ? v : 0.0f; }", "",
           "/* Deterministic test data; interp.py uses the same formula. */",
           "static void fill(float *buf, int count, int seed)", "{",
           "    for (int i = 0; i < count; i++)",
           "        buf[i] = (float)((i * 37 + seed * 101) % 201 - 100) / 100.0f;", "}", ""]
    for kernel in lowered["kernels"]:
        out += [kernel_c(kernel), ""]

    out.append("/* One buffer per tensor that lives in memory. */")
    for buf in lowered["buffers"]:
        node = graph.nodes[buf["name"]]
        decl = f"static float t_{buf['name']}[{buf['elements']}]"
        if node.op == "const":
            decl += " = {" + ", ".join(cfloat(v) for v in node.attrs["values"]) + "}"
        out.append(f"{decl};  /* {buf['kind']}, shape {buf['shape']} */")
    out += ["", "int main(void)", "{"]
    for buf in lowered["buffers"]:
        node = graph.nodes[buf["name"]]
        if node.op in ("input", "param"):
            out.append(f"    fill(t_{node.name}, {node.size}, {node.attrs['seed']});")
    for kernel in lowered["kernels"]:
        args = [f"t_{name}" for name in kernel["inputs"]] + [f"t_{kernel['output']}"]
        out.append(f"    {kernel['name']}({', '.join(args)});")
    for name in graph.outputs:
        node = graph.nodes[name]
        out += [f'    printf("output {name} {node.size}\\n");',
                f"    for (int i = 0; i < {node.size}; i++)",
                f'        printf("%.9g\\n", t_{name}[i]);']
    out += ["    return 0;", "}", ""]
    return "\n".join(out)
